/*
  Builds src/components/ui/solar-icons.tsx from the Iconify API.

  Run with `node scripts/gen-solar-icons.mjs` after changing ICONS. Each icon
  is fetched as an SVG, its inner markup is turned into JSX, and it is wrapped
  in a component that draws in currentColor at 1em.
*/
import { writeFile } from "node:fs/promises";

// Component name: Solar icon name. Bold for things and places, linear for
// small controls, and plug-circle-linear for MCP everywhere.
const ICONS = {
  AltArrowDown: "alt-arrow-down-linear",
  AltArrowRight: "alt-arrow-right-linear",
  HamburgerMenu: "hamburger-menu-linear",
  CheckCircle: "check-circle-linear",
  Magnifer: "magnifer-linear",
  Export: "export-linear",
  PlugCircle: "plug-circle-linear",
  Cpu: "cpu-bold",
  MagicStick: "magic-stick-3-bold",
  UserId: "user-id-bold",
  Database: "database-bold",
  LockKeyhole: "lock-keyhole-bold",
  Atom: "atom-bold",
  WalletMoney: "wallet-money-bold",
  History: "history-bold",
  Radar: "radar-bold",
  ShieldWarning: "shield-warning-bold",
  ShieldCheck: "shield-check-bold",
  Key: "key-bold",
  DangerTriangle: "danger-triangle-bold",
  ForbiddenCircle: "forbidden-circle-bold",
  PauseCircle: "pause-circle-bold",
  Lightbulb: "lightbulb-bolt-bold",
  ChatRoundDots: "chat-round-dots-bold",
  CodeSquare: "code-square-bold",
  DocumentText: "document-text-bold",
  Letter: "letter-bold",
  UsersGroupRounded: "users-group-rounded-bold",
  UserRounded: "user-rounded-bold",
};

const camel = (attr) => attr.replace(/-([a-z])/g, (_, c) => c.toUpperCase());

async function fetchIcon(name) {
  const res = await fetch(`https://api.iconify.design/solar/${name}.svg`);
  const text = await res.text();
  if (!res.ok || !text.startsWith("<svg")) throw new Error(`No Solar icon called ${name}`);
  const inner = text.replace(/^<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "");
  return inner
    .replace(/\s([a-z]+(?:-[a-z]+)+)=/g, (_, attr) => ` ${camel(attr)}=`)
    .replace(/<(\w+)([^>]*)><\/\1>/g, "<$1$2 />");
}

const parts = [];
for (const [component, name] of Object.entries(ICONS)) {
  const body = await fetchIcon(name);
  parts.push(`// solar:${name}\nexport function ${component}(props: IconProps) {\n  return <Icon {...props}>${body}</Icon>;\n}\n`);
}

const header = `/*
  Icons from the Solar set by 480 Design, licensed CC BY 4.0
  (https://creativecommons.org/licenses/by/4.0/). Generated by
  scripts/gen-solar-icons.mjs from the Iconify API; edit the list there and
  run it again rather than changing this file by hand.

  Each draws in currentColor at 1em, so it takes its colour and size from the
  text around it.
*/
import type { SVGProps } from "react";

export type IconProps = SVGProps<SVGSVGElement>;
export type IconComponent = (props: IconProps) => React.JSX.Element;

function Icon({ children, ...props }: IconProps) {
  return (
    <svg viewBox="0 0 24 24" width="1em" height="1em" fill="none" aria-hidden="true" focusable="false" {...props}>
      {children}
    </svg>
  );
}

`;

await writeFile(new URL("../src/components/ui/solar-icons.tsx", import.meta.url), header + parts.join("\n"));
console.log(`Wrote ${parts.length} icons`);
